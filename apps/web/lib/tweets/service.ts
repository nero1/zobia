export interface CreateTweetInput {
  userId: string;
  content: string | null;
  imageUrl?: string | null;
  video?: ParsedVideo | null;
  /** Set to reply to another Tweet — a reply is just a Tweet with this set. */
  parentTweetId?: string | null;
}

export interface CreateTweetResult {
  id: string;
  createdAt: string;
  imageCostCredits: number;
  imageCharged: boolean;
  longTweetCostCredits: number;
  longTweetCharged: boolean;
}

/**
 * Full Tweets creation pipeline: feature flag → level gate → parent lookup
 * (for replies) → length-charge + image-charge affordability checks →
 * atomic charge(s) + insert + mention rows + parent reply-count bump, all in
 * one DB transaction so a failed insert never leaves a user charged for
 * something that was never posted. Video embeds never cost anything.
 */
export async function createTweet(input: CreateTweetInput): Promise<CreateTweetResult> {
  await requireFeatureEnabled("tweets");

  if (!input.content?.trim() && !input.imageUrl && !input.video) {
    throw badRequest("A Tweet needs text, an image, or a video.", "TWEET_EMPTY");
  }
  const contentLength = input.content?.trim().length ?? 0;
  if (contentLength > TWEETS_HARD_CHAR_CAP) {
    throw badRequest(`Tweets cannot exceed ${TWEETS_HARD_CHAR_CAP} characters.`, "TWEET_TOO_LONG");
  }

  const eligibility = await getTweetsEligibility(input.userId);
  assertTweetsLevelGate(eligibility);

  if (input.parentTweetId) {
    const parent = await getTweet(input.parentTweetId);
    if (!parent) throw notFound("The Tweet you're replying to was not found");
  }

  const willChargeImage = Boolean(input.imageUrl) && eligibility.imageCostCredits > 0;
  if (input.imageUrl) assertCanAffordImage(eligibility);
  const willChargeLength = resolveLengthCharge(eligibility, contentLength);

  const mentionedUsernames = parseTweetMentions(input.content);
  const referenceId = `tweet_create:${input.userId}:${randomUUID()}`;

  const created = await db.transaction(async (tx: TransactionClient) => {
    if (willChargeImage) {
      await debitCoins(
        input.userId,
        eligibility.imageCostCredits,
        "tweet_image_created",
        referenceId,
        "Attached an image to a Tweet",
        {},
        tx
      );
    }
    if (willChargeLength) {
      await debitCoins(
        input.userId,
        eligibility.longTweetCostCredits,
        "tweet_long_created",
        referenceId,
        "Posted a long Tweet",
        { defaultMaxLength: eligibility.defaultMaxLength },
        tx
      );
    }

    const { rows } = await tx.query<{ id: string; created_at: string }>(
      `INSERT INTO tweets (user_id, parent_tweet_id, content, image_url, video_provider, video_url, video_embed_id)
       VALUES ($1, $2, $3, $4, $5, $6, $7)
       RETURNING id, created_at`,
      [
        input.userId,
        input.parentTweetId ?? null,
        input.content?.trim() || null,
        input.imageUrl ?? null,
        input.video?.videoProvider ?? null,
        input.video?.videoUrl ?? null,
        input.video?.videoEmbedId ?? null,
      ]
    );
    const tweet = rows[0];

    if (input.parentTweetId) {
      await tx.query(`UPDATE tweets SET replies_count = replies_count + 1 WHERE id = $1`, [input.parentTweetId]);
    }

    let mentionedUserIds: { id: string; username: string }[] = [];
    if (mentionedUsernames.length > 0) {
      const { rows: mentionRows } = await tx.query<{ id: string; username: string }>(
        `SELECT id, username FROM users WHERE LOWER(username) = ANY($1) AND deleted_at IS NULL`,
        [mentionedUsernames]
      );
      mentionedUserIds = mentionRows.filter((r) => r.id !== input.userId);
      for (const m of mentionedUserIds) {
        await tx.query(
          `INSERT INTO tweet_mentions (tweet_id, mentioned_user_id) VALUES ($1, $2)
           ON CONFLICT (tweet_id, mentioned_user_id) DO NOTHING`,
          [tweet.id, m.id]
        );
      }
    }

    return { tweet, mentionedUserIds };
  });

  // Fire mention notifications through the existing notifications pipeline,
  // best-effort — a notification failure must never undo a posted Tweet.
  if (created.mentionedUserIds.length > 0) {
    const { rows: authorRows } = await db.query<{ username: string }>(
      `SELECT username FROM users WHERE id = $1 LIMIT 1`,
      [input.userId]
    );
    const authorUsername = authorRows[0]?.username ?? "Someone";
    await Promise.all(
      created.mentionedUserIds.map((m) =>
        insertNotification(
          db,
          m.id,
          "tweet_mention",
          "You were mentioned in a Tweet",
          `@${authorUsername} mentioned you in a Tweet.`,
          { tweetId: created.tweet.id, authorUsername }
        )
      )
    ).catch((err) => logger.error({ err }, "[tweets] mention notification insert failed"));
  }

  return {
    id: created.tweet.id,
    createdAt: created.tweet.created_at,
    imageCostCredits: eligibility.imageCostCredits,
    imageCharged: willChargeImage,
    longTweetCostCredits: eligibility.longTweetCostCredits,
    longTweetCharged: willChargeLength,
  };
}

