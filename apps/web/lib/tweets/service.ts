/**
 * Extract `@username` tokens from tweet text (lowercased, de-duplicated).
 * Reuses the exact matching rule already used for Room chat @mentions
 * (lib/notifications/chatPush.ts's parseMentions) so `@username` parsing
 * behaves identically across the app.
 */
export function parseTweetMentions(text: string | null | undefined): string[] {
  if (!text) return [];
  const matches = text.matchAll(/(?:^|[^a-zA-Z0-9_])@([a-zA-Z0-9_]{3,30})/g);
  const set = new Set<string>();
  for (const m of matches) set.add(m[1].toLowerCase());
  return [...set];
}

