/**
 * Absolute, non-admin-configurable safety ceiling on Tweet content length —
 * mirrored as a DB CHECK constraint in 0001_consolidated_schema.sql. The real effective
 * limit (default vs. long-form vs. personal) is computed below and is
 * always <= this.
 */
export const TWEETS_HARD_CHAR_CAP = 7000;

/**
 * Rough average characters-per-word (5.1 avg English word length + 1 space,
 * per Wolfram Language corpus data) used to convert the admin's
 * `tweets_long_max_length` setting — deliberately expressed in WORDS per
 * product decision, since that's the more intuitive unit for an admin
 * setting a "long-form" ceiling — into an enforceable character count.
 */
const WORDS_TO_CHARS_FACTOR = 6;

export type TweetVideoProvider = "youtube" | "tiktok";

// ---------------------------------------------------------------------------
// Video URL parsing
// ---------------------------------------------------------------------------

const YOUTUBE_HOSTS = new Set(["youtube.com", "www.youtube.com", "m.youtube.com", "youtu.be"]);
const TIKTOK_HOSTS = new Set(["tiktok.com", "www.tiktok.com", "vm.tiktok.com", "vt.tiktok.com"]);

/** Extracts an 11-ish char YouTube video ID from any standard URL shape. */
export function parseYouTubeId(rawUrl: string): string | null {
  let u: URL;
  try {
    u = new URL(rawUrl);
  } catch {
    return null;
  }
  const host = u.hostname.toLowerCase();
  if (!YOUTUBE_HOSTS.has(host)) return null;

  if (host === "youtu.be") {
    const id = u.pathname.split("/").filter(Boolean)[0];
    return id && /^[\w-]{6,20}$/.test(id) ? id : null;
  }
  if (u.pathname === "/watch") {
    const id = u.searchParams.get("v");
    return id && /^[\w-]{6,20}$/.test(id) ? id : null;
  }
  const shortsMatch = u.pathname.match(/^\/shorts\/([\w-]{6,20})/);
  if (shortsMatch) return shortsMatch[1];
  const embedMatch = u.pathname.match(/^\/embed\/([\w-]{6,20})/);
  if (embedMatch) return embedMatch[1];
  return null;
}

/** Extracts a numeric TikTok video ID from a full-form `.../video/<id>` URL. */
function extractTikTokIdFromUrl(rawUrl: string): string | null {
  try {
    const u = new URL(rawUrl);
    const host = u.hostname.toLowerCase();
    if (!TIKTOK_HOSTS.has(host)) return null;
    const m = u.pathname.match(/\/video\/(\d+)/);
    return m ? m[1] : null;
  } catch {
    return null;
  }
}

/**
 * Resolves a TikTok URL to its numeric video ID.
 *
 * Design note (documented per task spec): TikTok share links come in two
 * shapes — the full form (`tiktok.com/@user/video/<id>`), whose ID we can
 * extract client-side with a regex, and short links (`vm.tiktok.com/<code>`,
 * `vt.tiktok.com/<code>`) generated by TikTok's native "Share > Copy Link"
 * button, which carry no ID in the URL itself — TikTok only reveals it after
 * following the redirect. We resolve those server-side at submit time with a
 * single GET request (redirect: "follow"), read the final resolved URL, and
 * extract the ID from it — this doubles as validating the link is a real,
 * reachable TikTok video before we accept it (an invalid/dead short link
 * fails to resolve to a `/video/<id>` path and is rejected). We didn't use
 * the public oEmbed endpoint (`tiktok.com/oembed`) instead because it 404s
 * on some private/region-locked videos that still resolve fine via a plain
 * redirect follow, and because we only need the ID (not the embed HTML) —
 * rendering uses TikTok's official `embed.js` blockquote embed client-side.
 */
export async function resolveTikTokId(rawUrl: string): Promise<string> {
  const direct = extractTikTokIdFromUrl(rawUrl);
  if (direct) return direct;

  let u: URL;
  try {
    u = new URL(rawUrl);
  } catch {
    throw badRequest("That doesn't look like a valid TikTok link.", "INVALID_TIKTOK_URL");
  }
  if (!TIKTOK_HOSTS.has(u.hostname.toLowerCase())) {
    throw badRequest("Video URL must be a youtube.com/youtu.be or tiktok.com link.", "INVALID_VIDEO_URL");
  }

  try {
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 5000);
    const res = await fetch(rawUrl, {
      method: "GET",
      redirect: "follow",
      signal: controller.signal,
      headers: { "User-Agent": "Mozilla/5.0 (compatible; ZobiaBot/1.0)" },
    }).finally(() => clearTimeout(timeout));
    const resolvedId = extractTikTokIdFromUrl(res.url);
    if (resolvedId) return resolvedId;
  } catch (err) {
    logger.error({ err, url: rawUrl }, "[tweets] TikTok short-link resolution failed");
  }

  throw badRequest(
    "Couldn't resolve that TikTok link. Paste the full video URL (tiktok.com/@user/video/...) instead of a shortened share link.",
    "INVALID_TIKTOK_URL"
  );
}

export interface ParsedVideo {
  videoProvider: TweetVideoProvider;
  videoUrl: string;
  videoEmbedId: string;
}

/** Validates and parses a video URL submitted for a Tweet's video embed. */
export async function parseTweetVideo(
  provider: TweetVideoProvider,
  rawUrl: string
): Promise<ParsedVideo> {
  if (provider === "youtube") {
    const id = parseYouTubeId(rawUrl);
    if (!id) throw badRequest("That doesn't look like a valid YouTube video URL.", "INVALID_VIDEO_URL");
    return { videoProvider: "youtube", videoUrl: rawUrl, videoEmbedId: id };
  }
  const id = await resolveTikTokId(rawUrl);
  return { videoProvider: "tiktok", videoUrl: rawUrl, videoEmbedId: id };
}

