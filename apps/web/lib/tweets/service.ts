export interface TweetsEligibility {
  rankNumber: number;
  xpTotal: number;
  creditBalance: number;
  minLevel: number;
  imageCostCredits: number;
  /** Standard length limit (characters) for non-exempt users. */
  defaultMaxLength: number;
  /** True if this user gets free long-form Tweets (role/plan OR level exempt). */
  isLongFormExempt: boolean;
  /** Admin long-form ceiling, converted from tweets_long_max_length (words) to characters. */
  longMaxLengthChars: number;
  /** This user's personal effective max length (chars), clamped to [defaultMaxLength, longMaxLengthChars]. */
  personalMaxLength: number;
  /** Credits charged for a Tweet over defaultMaxLength when NOT long-form exempt. */
  longTweetCostCredits: number;
}

export async function getTweetsEligibility(userId: string): Promise<TweetsEligibility> {
  const [manifest, userRows] = await Promise.all([
    loadManifest(),
    db.query<{
      xp_total: number;
      coin_balance: number;
      plan: string;
      prestige_count: number | null;
      is_admin: boolean | null;
      is_moderator: boolean | null;
      tweet_max_length: number | null;
    }>(
      `SELECT COALESCE(xp_total, 0) AS xp_total, COALESCE(coin_balance, 0) AS coin_balance,
              plan, prestige_count, is_admin, is_moderator, tweet_max_length
       FROM users WHERE id = $1 AND deleted_at IS NULL LIMIT 1`,
      [userId]
    ),
  ]);
  const row = userRows.rows[0];
  if (!row) throw forbidden("User account not found");
  const rankNumber = getRankForXP(row.xp_total).rankNumber;

  const { defaultMaxLength, longMinLevel, longMinRoles, longMaxLengthWords, imageCostCredits, longTweetCostCredits, minLevel } =
    manifest.tweets;

  const isLongFormExempt =
    rankNumber >= longMinLevel ||
    isPlanEligible(row.plan ?? "free", row.prestige_count ?? 0, longMinRoles, {
      isAdmin: Boolean(row.is_admin),
      isModerator: Boolean(row.is_moderator),
    });

  const longMaxLengthChars = Math.min(longMaxLengthWords * WORDS_TO_CHARS_FACTOR, TWEETS_HARD_CHAR_CAP);
  const personalMaxLength = Math.min(
    Math.max(row.tweet_max_length ?? defaultMaxLength, defaultMaxLength),
    longMaxLengthChars
  );

  return {
    rankNumber,
    xpTotal: row.xp_total,
    creditBalance: row.coin_balance,
    minLevel,
    imageCostCredits,
    defaultMaxLength,
    isLongFormExempt,
    longMaxLengthChars,
    personalMaxLength,
    longTweetCostCredits,
  };
}

/**
 * Clamps a user-requested personal tweet-length preference to
 * [defaultMaxLength, longMaxLengthChars] for storage in
 * `users.tweet_max_length`. Used by PATCH /api/users/me/settings.
 */
export async function clampPersonalTweetMaxLength(userId: string, requested: number): Promise<number> {
  const eligibility = await getTweetsEligibility(userId);
  return Math.min(Math.max(requested, eligibility.defaultMaxLength), eligibility.longMaxLengthChars);
}

export function assertTweetsLevelGate(eligibility: TweetsEligibility): void {
  if (eligibility.rankNumber < eligibility.minLevel) {
    throw forbidden(
      `You must reach Level ${eligibility.minLevel} to post Tweets. Your current level is ${eligibility.rankNumber}.`,
      "TWEETS_LEVEL_TOO_LOW",
      { minLevel: eligibility.minLevel, currentLevel: eligibility.rankNumber }
    );
  }
}

function assertCanAffordImage(eligibility: TweetsEligibility): void {
  if (eligibility.imageCostCredits <= 0) return;
  if (eligibility.creditBalance < eligibility.imageCostCredits) {
    throw new ApiError(
      402,
      "INSUFFICIENT_TWEET_IMAGE_FUNDS",
      "You don't have enough Credits to attach an image to a Tweet.",
      undefined,
      undefined,
      { costCredits: eligibility.imageCostCredits, creditBalance: eligibility.creditBalance }
    );
  }
}

/**
 * Determines whether (and how much) a specific Tweet's content length must
 * be charged for, given the caller's eligibility. Throws TWEET_TOO_LONG if
 * the content exceeds the caller's personal max length (or the hard cap),
 * and a 402 INSUFFICIENT_TWEET_LENGTH_FUNDS if it's chargeable but the
 * caller can't afford it.
 */
function resolveLengthCharge(eligibility: TweetsEligibility, contentLength: number): boolean {
  if (contentLength <= eligibility.defaultMaxLength) return false;

  if (contentLength > eligibility.personalMaxLength) {
    throw new ApiError(
      400,
      "TWEET_TOO_LONG",
      eligibility.isLongFormExempt
        ? `Tweets are limited to ${eligibility.personalMaxLength} characters for your account. Raise your personal limit in Settings (up to ${eligibility.longMaxLengthChars}).`
        : `Tweets over ${eligibility.defaultMaxLength} characters cost ${eligibility.longTweetCostCredits} Credits, up to ${eligibility.personalMaxLength} characters.`,
      undefined,
      undefined,
      { maxLength: eligibility.personalMaxLength }
    );
  }

  if (eligibility.isLongFormExempt) return false; // free long tweet, up to personalMaxLength

  if (eligibility.creditBalance < eligibility.longTweetCostCredits) {
    throw new ApiError(
      402,
      "INSUFFICIENT_TWEET_LENGTH_FUNDS",
      `You don't have enough Credits to post a Tweet over ${eligibility.defaultMaxLength} characters.`,
      undefined,
      undefined,
      { costCredits: eligibility.longTweetCostCredits, creditBalance: eligibility.creditBalance, defaultMaxLength: eligibility.defaultMaxLength }
    );
  }
  return true; // charge longTweetCostCredits
}

